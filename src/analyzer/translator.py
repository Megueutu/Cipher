import re

_MULTI = [
    (r"\|_\|", "u"),
    (r"\\/\\/", "w"),
    (r"\\/", "v"),
    (r"\|\)", "d"),
    (r"\|<", "k"),
    (r"\|{", "k"),
    (r"\(\)", "o"),
    (r"\[\]", "o"),
    (r"\{\}", "o"),
    (r"\|\*", "p"),
    (r"\|>", "p"),
    (r"><", "x"),
    (r"`/", "y"),
    (r"'/", "y"),
    (r"`\)", "j"),
    (r"_\|", "j"),
    (r"\|_", "l"),
    (r"\|/", "y"),
    (r"/\\", "a"),
    (r"/-\\", "a"),
    (r"/_\\" , "a"),
    (r"\|3", "b"),
    (r"13", "b"),
    (r"\(", "c"),
    (r"<", "c"),
    (r"\[\)", "d"),
    (r"\[-", "e"),
    (r"ph", "f"),
    (r"\|-", "f"),
    (r"\(_\+", "g"),
    (r"#", "h"),
    (r"\|-?\|", "h"),
    (r"\|=", "f"),
    (r"_/", "j"),
    (r"\|\\", "n"),
    (r"/\\/", "n"),
    (r"\|\|", "n"),
    (r"\|o", "q"),
    (r"12", "r"),
    (r"\|2", "r"),
    (r"5", "s"),
    (r"\|\|_", "u"),
    (r"\\\|/", "m"),
    (r"/\\\\", "m"),
]
_ALPH = str.maketrans({
    "@": "a",
    "4": "a",
    "8": "b",
    "6": "b",
    "(": "c",
    "<": "c",
    "3": "e",
    "9": "g",
    "1": "i",
    "!": "i",
    "|": "i",
    "£": "l",
    "0": "o",
    "$": "s",
    "5": "s",
    "7": "t",
    "+": "t",
    "2": "z",
})

def translate_password(password: str) -> str:
    for pattern, letter in _MULTI:
        password = re.sub(pattern, letter, password)
    
    return password.translate(_ALPH)
